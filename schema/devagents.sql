-- Subjective DevAgents — Cloudflare D1 database `devagents`.
--
-- One unified record of every conversation we hold with any LLM, whether it was reached
-- through a subscription seat (a `codex`/`claude`/`cursor` CLI logged in as an OS user) or
-- a metered API key. The point is that a chat looks the same here regardless of how it was
-- paid for or which vendor answered it.
--
-- The spine is four levels, widest to narrowest:
--
--   conversations          our own global id; survives provider and account switches
--     conversation_sessions  the provider's OWN id (a codex/claude session uuid, a Cursor
--                            composer id, an OpenAI response id) — one conversation can
--                            own several, because "Continue as <user>" and cross-provider
--                            handoff both start a fresh provider-side session
--       turns                one user request and everything the agent did answering it
--         messages           the text: what the user sent, what the LLM replied
--         thoughts           the reasoning steps reported before the response
--         tool_calls         bash / web / MCP invocations made during the turn
--         document_accesses  files and documents the agent read or wrote
--         authorization_requests  "may I do this?" and the human's decision
--         user_prompts       questions the agent asked the human, and the answer
--         attachments        images and files carried in or produced
--         usage_records      tokens and cost per model call (an agentic turn makes many)
--
-- Every element table carries (turn_id, seq) so the whole exchange can be replayed in
-- order; `v_turn_timeline` unions them into that single stream, which is why there is no
-- separate events table to keep in sync.
--
-- Conventions follow schema/worktwins.sql: TEXT primary keys (uuid/ulid generated by the
-- caller), ISO-8601 UTC strings for timestamps, CHECK constraints for enums, `_json`
-- suffix for embedded JSON, and no triggers or generated columns so the file stays
-- portable between D1 and plain SQLite.

PRAGMA foreign_keys = ON;

-- ---------------------------------------------------------------------------------------
-- Catalog: who we can talk to, and how we are allowed to pay for it
-- ---------------------------------------------------------------------------------------

-- A vendor or CLI we can route a conversation to. `access_modes` records which of the two
-- billing worlds this provider supports, since some (Cursor) are subscription-only for us
-- while others (OpenAI, Anthropic) offer both.
CREATE TABLE IF NOT EXISTS providers (
  id TEXT PRIMARY KEY,                       -- 'codex', 'claude', 'cursor', 'openai', 'anthropic', 'gemini', 'grok'
  display_name TEXT NOT NULL,                -- 'Codex', 'Claude', 'Cursor'
  vendor TEXT NOT NULL,                      -- 'openai', 'anthropic', 'google', 'xai', 'cursor'
  kind TEXT NOT NULL CHECK (kind IN ('cli', 'api', 'ide')),
  access_modes TEXT NOT NULL DEFAULT 'subscription,api',  -- comma list of allowed auth_mode values
  supports_resume INTEGER NOT NULL DEFAULT 1 CHECK (supports_resume IN (0, 1)),
  supports_thinking INTEGER NOT NULL DEFAULT 0 CHECK (supports_thinking IN (0, 1)),
  supports_tools INTEGER NOT NULL DEFAULT 1 CHECK (supports_tools IN (0, 1)),
  supports_attachments INTEGER NOT NULL DEFAULT 0 CHECK (supports_attachments IN (0, 1)),
  icon_path TEXT,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'deprecated', 'disabled')),
  metadata_json TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

-- Model catalog with the prices used to turn tokens into money. Prices are per MILLION
-- tokens and are the list price at the time of writing; a usage_record snapshots the cost
-- it actually computed, so re-pricing later never rewrites history.
CREATE TABLE IF NOT EXISTS models (
  id TEXT PRIMARY KEY,                       -- 'claude-opus-5', 'gpt-5.1-codex'
  provider_id TEXT NOT NULL REFERENCES providers(id) ON DELETE CASCADE,
  display_name TEXT NOT NULL,
  family TEXT,                               -- 'claude', 'gpt', 'gemini'
  context_window_tokens INTEGER,
  max_output_tokens INTEGER,
  price_input_per_mtok REAL,
  price_output_per_mtok REAL,
  price_cache_read_per_mtok REAL,
  price_cache_write_per_mtok REAL,
  supports_reasoning INTEGER NOT NULL DEFAULT 0 CHECK (supports_reasoning IN (0, 1)),
  supports_vision INTEGER NOT NULL DEFAULT 0 CHECK (supports_vision IN (0, 1)),
  is_default INTEGER NOT NULL DEFAULT 0 CHECK (is_default IN (0, 1)),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'deprecated', 'retired')),
  released_at TEXT,
  metadata_json TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

-- One way of reaching a provider: either a subscription seat (a CLI already logged in
-- under some OS user's $HOME — which is why os_user matters and why credentials are never
-- stored here) or a metered API key held in a secret store. This table is what makes the
-- system unified: a conversation points at an account, not at a billing model.
CREATE TABLE IF NOT EXISTS provider_accounts (
  id TEXT PRIMARY KEY,
  provider_id TEXT NOT NULL REFERENCES providers(id) ON DELETE CASCADE,
  label TEXT NOT NULL,                       -- 'Claude Max — goldenthinker', 'OpenAI prod key'
  auth_mode TEXT NOT NULL CHECK (auth_mode IN ('subscription', 'api')),
  owner_user_id TEXT,                        -- our platform user who owns the seat/key
  os_user TEXT,                              -- subscription mode: whose $HOME holds the CLI login
  host TEXT,                                 -- machine the CLI login lives on
  -- Never the key itself: only where to find it (env var name, secret binding, KV id).
  credential_ref TEXT,
  plan_name TEXT,                            -- 'max_20x', 'team', 'pay_as_you_go'
  seat_limit INTEGER,
  is_default INTEGER NOT NULL DEFAULT 0 CHECK (is_default IN (0, 1)),
  status TEXT NOT NULL DEFAULT 'active'
    CHECK (status IN ('active', 'expired', 'revoked', 'rate_limited', 'unauthenticated', 'disabled')),
  last_verified_at TEXT,
  metadata_json TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

-- Subscription plans meter by rolling window (a 5-hour cap, a weekly cap) rather than by
-- token price, so "how much of my allowance is left" cannot be derived from usage_records
-- alone. One row per account per window.
CREATE TABLE IF NOT EXISTS account_usage_windows (
  id TEXT PRIMARY KEY,
  account_id TEXT NOT NULL REFERENCES provider_accounts(id) ON DELETE CASCADE,
  window_kind TEXT NOT NULL CHECK (window_kind IN ('rolling_5h', 'daily', 'weekly', 'monthly', 'custom')),
  window_start TEXT NOT NULL,
  window_end TEXT NOT NULL,
  used_tokens INTEGER NOT NULL DEFAULT 0,
  used_requests INTEGER NOT NULL DEFAULT 0,
  limit_tokens INTEGER,
  limit_requests INTEGER,
  utilization_pct REAL,                      -- what the provider itself reported, when it does
  exhausted_at TEXT,
  metadata_json TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

-- ---------------------------------------------------------------------------------------
-- Conversation spine
-- ---------------------------------------------------------------------------------------

-- The global conversation id — ours, stable for the life of the chat. It deliberately
-- outlives the provider session: switching OS user, resuming after a restart, or handing
-- the transcript to a different vendor all keep this id and add a new row to
-- conversation_sessions.
CREATE TABLE IF NOT EXISTS conversations (
  id TEXT PRIMARY KEY,
  -- The devagents client's own routing string (`llm:<provider>:<b64>`), kept so existing
  -- on-disk state maps onto this database without a rewrite.
  target TEXT UNIQUE,
  title TEXT NOT NULL,
  title_source TEXT NOT NULL DEFAULT 'derived' CHECK (title_source IN ('derived', 'user', 'provider')),
  owner_user_id TEXT,
  os_user TEXT,                              -- OS account the chat currently runs as
  workspace TEXT,                            -- working directory the agent operates in
  -- Denormalised "who is answering right now": the authoritative history is the ordered
  -- conversation_sessions rows, but almost every list query wants this without a join.
  current_session_id TEXT,
  current_provider_id TEXT REFERENCES providers(id) ON DELETE SET NULL,
  origin TEXT NOT NULL DEFAULT 'local' CHECK (origin IN ('local', 'imported', 'api', 'web')),
  visibility TEXT NOT NULL DEFAULT 'private' CHECK (visibility IN ('private', 'team', 'public')),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'archived', 'deleted')),
  irc_channel TEXT,
  -- Rollups maintained by the writer so a sidebar listing never aggregates child tables.
  message_count INTEGER NOT NULL DEFAULT 0,
  turn_count INTEGER NOT NULL DEFAULT 0,
  total_tokens INTEGER NOT NULL DEFAULT 0,
  total_cost_usd REAL NOT NULL DEFAULT 0,
  first_message_at TEXT,
  last_activity_at TEXT,
  tags_json TEXT,
  metadata_json TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

-- The provider's OWN conversation id, as the user asked for: `provider_session_id` is
-- whatever that vendor calls it (codex/claude session uuid, Cursor composer id, OpenAI
-- response/thread id). Unique per provider so the same uuid from two vendors cannot
-- collide, and ordered within the conversation by `seq`.
CREATE TABLE IF NOT EXISTS conversation_sessions (
  id TEXT PRIMARY KEY,
  conversation_id TEXT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  seq INTEGER NOT NULL,                      -- 1, 2, 3… order the sessions were opened
  provider_id TEXT NOT NULL REFERENCES providers(id) ON DELETE RESTRICT,
  account_id TEXT REFERENCES provider_accounts(id) ON DELETE SET NULL,
  model_id TEXT REFERENCES models(id) ON DELETE SET NULL,
  provider_session_id TEXT,                  -- NULL until the provider hands one back
  parent_session_id TEXT REFERENCES conversation_sessions(id) ON DELETE SET NULL,
  -- Why this session exists rather than reusing the previous one. 'os_user_switch' and
  -- 'provider_switch' are the "Continue as…" paths, where no session can be carried
  -- across because each CLI's session store lives in its own $HOME.
  start_reason TEXT NOT NULL DEFAULT 'new'
    CHECK (start_reason IN ('new', 'resume', 'os_user_switch', 'provider_switch', 'fork', 'import', 'recovery')),
  os_user TEXT,
  workspace TEXT,
  source_file TEXT,                          -- transcript on disk, when imported/mirrored
  system_prompt TEXT,
  tools_json TEXT,                           -- tool schema offered to the model
  params_json TEXT,                          -- temperature, reasoning effort, sandbox mode…
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed', 'expired', 'failed')),
  started_at TEXT NOT NULL,
  ended_at TEXT,
  metadata_json TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  UNIQUE (conversation_id, seq)
);

-- One user request and the whole agent loop that answered it. Tokens and cost live here as
-- a rollup of the turn's usage_records, because an agentic turn makes many model calls.
CREATE TABLE IF NOT EXISTS turns (
  id TEXT PRIMARY KEY,
  conversation_id TEXT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  session_id TEXT NOT NULL REFERENCES conversation_sessions(id) ON DELETE CASCADE,
  seq INTEGER NOT NULL,                      -- turn number within the conversation
  initiator TEXT NOT NULL DEFAULT 'user' CHECK (initiator IN ('user', 'agent', 'system', 'schedule', 'irc')),
  status TEXT NOT NULL DEFAULT 'running'
    CHECK (status IN ('running', 'completed', 'failed', 'cancelled', 'timeout', 'awaiting_input', 'awaiting_authorization')),
  error_kind TEXT
    CHECK (error_kind IS NULL OR error_kind IN
      ('authentication_required', 'rate_limited', 'timeout', 'read_only', 'os_user_not_connected',
       'runtime_missing', 'runtime_error', 'busy', 'invalid_request', 'cancelled', 'unknown')),
  error_message TEXT,
  input_tokens INTEGER NOT NULL DEFAULT 0,
  output_tokens INTEGER NOT NULL DEFAULT 0,
  cache_read_tokens INTEGER NOT NULL DEFAULT 0,
  cache_write_tokens INTEGER NOT NULL DEFAULT 0,
  reasoning_tokens INTEGER NOT NULL DEFAULT 0,
  total_tokens INTEGER NOT NULL DEFAULT 0,
  cost_usd REAL NOT NULL DEFAULT 0,
  model_call_count INTEGER NOT NULL DEFAULT 0,
  started_at TEXT NOT NULL,
  first_token_at TEXT,                       -- time to first token, for latency tracking
  ended_at TEXT,
  duration_ms INTEGER,
  metadata_json TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  UNIQUE (conversation_id, seq)
);

-- The chat text itself: what the user sent, what the LLM sent back. `content` is the clean
-- visible text (envelope blocks already stripped); `content_raw` keeps the original when
-- they differ, so cleaning rules can be revised without re-importing.
CREATE TABLE IF NOT EXISTS messages (
  id TEXT PRIMARY KEY,
  conversation_id TEXT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  session_id TEXT REFERENCES conversation_sessions(id) ON DELETE SET NULL,
  turn_id TEXT REFERENCES turns(id) ON DELETE CASCADE,
  seq INTEGER NOT NULL,                      -- order within the turn
  role TEXT NOT NULL CHECK (role IN ('user', 'assistant', 'system', 'tool', 'tool_output')),
  content TEXT,
  content_raw TEXT,
  content_format TEXT NOT NULL DEFAULT 'markdown' CHECK (content_format IN ('markdown', 'text', 'json', 'html')),
  -- The provider's own id for this message, when it exposes one; lets an incremental
  -- re-import recognise a message it already stored.
  provider_message_id TEXT,
  author_label TEXT,                         -- 'You', 'Claude', an IRC nick
  token_count INTEGER,
  is_partial INTEGER NOT NULL DEFAULT 0 CHECK (is_partial IN (0, 1)),
  send_failed INTEGER NOT NULL DEFAULT 0 CHECK (send_failed IN (0, 1)),
  error_message TEXT,
  sent_at TEXT NOT NULL,
  metadata_json TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

-- ---------------------------------------------------------------------------------------
-- Chat elements — the things a conversation does besides emitting prose
-- ---------------------------------------------------------------------------------------

-- The list of thoughts an agent reports before printing its response. Kept apart from
-- messages because it is separately billed (reasoning tokens), separately redacted, and
-- usually hidden in the UI behind a disclosure.
CREATE TABLE IF NOT EXISTS thoughts (
  id TEXT PRIMARY KEY,
  conversation_id TEXT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  turn_id TEXT NOT NULL REFERENCES turns(id) ON DELETE CASCADE,
  seq INTEGER NOT NULL,                      -- order of the thought within the turn
  content TEXT,                              -- NULL when the provider redacts it
  summary TEXT,                              -- short headline some providers emit
  -- Providers return encrypted/opaque reasoning that must be replayed verbatim to be
  -- accepted on the next request; keep it rather than reconstructing it.
  signature TEXT,
  is_redacted INTEGER NOT NULL DEFAULT 0 CHECK (is_redacted IN (0, 1)),
  token_count INTEGER,
  started_at TEXT,
  ended_at TEXT,
  duration_ms INTEGER,
  metadata_json TEXT,
  created_at TEXT NOT NULL
);

-- Any tool the agent invoked. document_accesses and authorization_requests both point back
-- here when they arose from a tool call, which is the usual case.
CREATE TABLE IF NOT EXISTS tool_calls (
  id TEXT PRIMARY KEY,
  conversation_id TEXT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  turn_id TEXT NOT NULL REFERENCES turns(id) ON DELETE CASCADE,
  seq INTEGER NOT NULL,
  provider_call_id TEXT,                     -- vendor's tool_use id, for matching results
  tool_name TEXT NOT NULL,                   -- 'bash', 'read_file', 'web_search', an MCP tool
  tool_kind TEXT NOT NULL DEFAULT 'other'
    CHECK (tool_kind IN ('shell', 'file', 'search', 'web', 'mcp', 'subagent', 'code', 'other')),
  server_name TEXT,                          -- MCP server the tool came from
  arguments_json TEXT,
  result_text TEXT,
  result_truncated INTEGER NOT NULL DEFAULT 0 CHECK (result_truncated IN (0, 1)),
  exit_code INTEGER,
  status TEXT NOT NULL DEFAULT 'completed'
    CHECK (status IN ('pending', 'running', 'completed', 'failed', 'denied', 'cancelled', 'timeout')),
  error_message TEXT,
  workdir TEXT,
  started_at TEXT,
  ended_at TEXT,
  duration_ms INTEGER,
  metadata_json TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

-- Every document or file the chat touched. Separate from tool_calls so "what has this agent
-- read from my disk?" is one indexed query rather than a scan of tool arguments — the
-- question people actually ask when auditing an agent.
CREATE TABLE IF NOT EXISTS document_accesses (
  id TEXT PRIMARY KEY,
  conversation_id TEXT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  turn_id TEXT NOT NULL REFERENCES turns(id) ON DELETE CASCADE,
  tool_call_id TEXT REFERENCES tool_calls(id) ON DELETE SET NULL,
  seq INTEGER NOT NULL,
  access_kind TEXT NOT NULL
    CHECK (access_kind IN ('read', 'write', 'create', 'append', 'delete', 'rename', 'search', 'list', 'fetch')),
  resource_type TEXT NOT NULL DEFAULT 'file'
    CHECK (resource_type IN ('file', 'directory', 'url', 'repository', 'database', 'artifact', 'connector')),
  uri TEXT NOT NULL,                         -- absolute path, URL, or connector locator
  display_name TEXT,
  mime_type TEXT,
  byte_size INTEGER,
  line_start INTEGER,                        -- which slice was read, when partial
  line_end INTEGER,
  content_sha256 TEXT,                       -- detects a file changing under the agent
  was_truncated INTEGER NOT NULL DEFAULT 0 CHECK (was_truncated IN (0, 1)),
  outside_workspace INTEGER NOT NULL DEFAULT 0 CHECK (outside_workspace IN (0, 1)),
  authorization_id TEXT,                     -- set when the access needed explicit approval
  status TEXT NOT NULL DEFAULT 'succeeded' CHECK (status IN ('succeeded', 'failed', 'denied')),
  error_message TEXT,
  accessed_at TEXT NOT NULL,
  metadata_json TEXT,
  created_at TEXT NOT NULL
);

-- "May I run this / write that / call this tool?" and what the human decided. The decision
-- is state that arrives later than the request, so this is its own row rather than a field
-- on the tool call.
CREATE TABLE IF NOT EXISTS authorization_requests (
  id TEXT PRIMARY KEY,
  conversation_id TEXT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  turn_id TEXT NOT NULL REFERENCES turns(id) ON DELETE CASCADE,
  tool_call_id TEXT REFERENCES tool_calls(id) ON DELETE SET NULL,
  seq INTEGER NOT NULL,
  request_kind TEXT NOT NULL
    CHECK (request_kind IN ('tool_use', 'file_write', 'file_delete', 'shell_command', 'network_access',
                            'credential_access', 'spend', 'external_send', 'other')),
  title TEXT NOT NULL,                       -- short line shown in the approval prompt
  detail TEXT,
  requested_action TEXT,                     -- the exact command/path/endpoint at stake
  risk_level TEXT NOT NULL DEFAULT 'normal' CHECK (risk_level IN ('low', 'normal', 'high', 'destructive')),
  decision TEXT NOT NULL DEFAULT 'pending'
    CHECK (decision IN ('pending', 'allowed', 'allowed_always', 'denied', 'denied_always', 'expired', 'auto_allowed')),
  -- How the decision was reached: a human clicking, or a standing rule/permission mode.
  decided_by TEXT CHECK (decided_by IS NULL OR decided_by IN ('user', 'policy', 'permission_mode', 'timeout')),
  decided_by_user_id TEXT,
  decision_reason TEXT,
  -- 'always' answers are remembered against this scope so the same ask is not repeated.
  scope TEXT NOT NULL DEFAULT 'once' CHECK (scope IN ('once', 'turn', 'session', 'conversation', 'workspace', 'global')),
  requested_at TEXT NOT NULL,
  decided_at TEXT,
  expires_at TEXT,
  metadata_json TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

-- A question the chat asked the human — a clarification, a multiple choice, a form. Like
-- authorizations these carry pending state, and a turn can legitimately sit in
-- 'awaiting_input' until one is answered.
CREATE TABLE IF NOT EXISTS user_prompts (
  id TEXT PRIMARY KEY,
  conversation_id TEXT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  turn_id TEXT NOT NULL REFERENCES turns(id) ON DELETE CASCADE,
  seq INTEGER NOT NULL,
  prompt_kind TEXT NOT NULL DEFAULT 'question'
    CHECK (prompt_kind IN ('question', 'choice', 'multi_choice', 'confirmation', 'form', 'credential', 'file_request')),
  question TEXT NOT NULL,
  header TEXT,                               -- short label for the chip/tag in the UI
  -- [{value, label, description}] — the offered answers, when the ask is a choice.
  options_json TEXT,
  allows_free_text INTEGER NOT NULL DEFAULT 1 CHECK (allows_free_text IN (0, 1)),
  is_blocking INTEGER NOT NULL DEFAULT 1 CHECK (is_blocking IN (0, 1)),
  answer_text TEXT,
  answer_values_json TEXT,                   -- selected option values, for choice prompts
  answered_by_user_id TEXT,
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'answered', 'dismissed', 'cancelled', 'expired', 'superseded')),
  asked_at TEXT NOT NULL,
  answered_at TEXT,
  expires_at TEXT,
  metadata_json TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

-- Images pasted into the composer, files the agent produced, screenshots. Bytes live in R2
-- (or on disk); this table holds the pointer and the provenance.
CREATE TABLE IF NOT EXISTS attachments (
  id TEXT PRIMARY KEY,
  conversation_id TEXT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  turn_id TEXT REFERENCES turns(id) ON DELETE CASCADE,
  message_id TEXT REFERENCES messages(id) ON DELETE CASCADE,
  seq INTEGER NOT NULL DEFAULT 0,
  direction TEXT NOT NULL CHECK (direction IN ('inbound', 'outbound')),
  filename TEXT NOT NULL,
  mime_type TEXT,
  byte_size INTEGER,
  storage_kind TEXT NOT NULL DEFAULT 'r2' CHECK (storage_kind IN ('r2', 'local', 'inline', 'url')),
  storage_ref TEXT,                          -- R2 key, local path, or URL
  content_sha256 TEXT,
  width INTEGER,
  height INTEGER,
  metadata_json TEXT,
  created_at TEXT NOT NULL
);

-- ---------------------------------------------------------------------------------------
-- Accounting
-- ---------------------------------------------------------------------------------------

-- Tokens and cost for ONE model call. A single agentic turn can make dozens, so this is
-- deliberately finer-grained than the turn: turns.total_tokens is the rollup of these.
--
-- `billing_mode` is what unifies subscription and API usage: a subscription call still
-- reports tokens (worth tracking against the plan's window) but bills nothing per token,
-- so cost_usd is 0 there and only api rows contribute to spend.
CREATE TABLE IF NOT EXISTS usage_records (
  id TEXT PRIMARY KEY,
  conversation_id TEXT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  session_id TEXT REFERENCES conversation_sessions(id) ON DELETE SET NULL,
  turn_id TEXT REFERENCES turns(id) ON DELETE CASCADE,
  account_id TEXT REFERENCES provider_accounts(id) ON DELETE SET NULL,
  provider_id TEXT NOT NULL REFERENCES providers(id) ON DELETE RESTRICT,
  model_id TEXT REFERENCES models(id) ON DELETE SET NULL,
  model_name_raw TEXT,                       -- exactly what the provider reported
  seq INTEGER NOT NULL DEFAULT 0,
  billing_mode TEXT NOT NULL CHECK (billing_mode IN ('subscription', 'api', 'free', 'unknown')),
  request_id TEXT,                           -- vendor request id, for reconciling invoices
  input_tokens INTEGER NOT NULL DEFAULT 0,
  output_tokens INTEGER NOT NULL DEFAULT 0,
  cache_read_tokens INTEGER NOT NULL DEFAULT 0,
  cache_write_tokens INTEGER NOT NULL DEFAULT 0,
  reasoning_tokens INTEGER NOT NULL DEFAULT 0,
  total_tokens INTEGER NOT NULL DEFAULT 0,
  -- Cost snapshotted at write time from the model's price columns, so later re-pricing
  -- never rewrites what we already reported.
  cost_usd REAL NOT NULL DEFAULT 0,
  price_snapshot_json TEXT,
  is_estimated INTEGER NOT NULL DEFAULT 0 CHECK (is_estimated IN (0, 1)),
  latency_ms INTEGER,
  recorded_at TEXT NOT NULL,
  metadata_json TEXT,
  created_at TEXT NOT NULL
);

-- ---------------------------------------------------------------------------------------
-- Ingestion bookkeeping
-- ---------------------------------------------------------------------------------------

-- Maps a local transcript on disk (a Codex/Claude/Cursor session file) to the conversation
-- it produced, with the fingerprint the incremental importer uses to skip unchanged files.
-- Without this the history scan re-imports tens of thousands of files every run.
CREATE TABLE IF NOT EXISTS import_sources (
  id TEXT PRIMARY KEY,
  conversation_id TEXT REFERENCES conversations(id) ON DELETE SET NULL,
  session_id TEXT REFERENCES conversation_sessions(id) ON DELETE SET NULL,
  provider_id TEXT REFERENCES providers(id) ON DELETE SET NULL,
  source_kind TEXT NOT NULL DEFAULT 'file'
    CHECK (source_kind IN ('file', 'sqlite', 'api_export', 'manifest')),
  source_uri TEXT NOT NULL UNIQUE,           -- absolute path or locator on the scanned host
  source_user TEXT,                          -- whose $HOME it came from
  host TEXT,
  fingerprint TEXT,                          -- mtime_ns:size, or a content hash
  message_count INTEGER NOT NULL DEFAULT 0,
  last_activity_at TEXT,
  imported_at TEXT,
  import_status TEXT NOT NULL DEFAULT 'pending'
    CHECK (import_status IN ('pending', 'imported', 'skipped', 'failed', 'stale')),
  error_message TEXT,
  metadata_json TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

-- ---------------------------------------------------------------------------------------
-- Indexes — driven by the queries the UI and the accounting actually run
-- ---------------------------------------------------------------------------------------

-- Sidebar: newest conversations for an owner.
CREATE INDEX IF NOT EXISTS idx_conversations_activity ON conversations(status, last_activity_at DESC);
CREATE INDEX IF NOT EXISTS idx_conversations_owner ON conversations(owner_user_id, last_activity_at DESC);
CREATE INDEX IF NOT EXISTS idx_conversations_provider ON conversations(current_provider_id, last_activity_at DESC);

-- "Which of our conversations is this provider session?" — the reverse lookup used when a
-- CLI transcript is re-scanned and has to be matched back to a known chat.
CREATE UNIQUE INDEX IF NOT EXISTS idx_sessions_provider_session
  ON conversation_sessions(provider_id, provider_session_id)
  WHERE provider_session_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_sessions_conversation ON conversation_sessions(conversation_id, seq);
CREATE INDEX IF NOT EXISTS idx_sessions_account ON conversation_sessions(account_id, started_at DESC);

CREATE INDEX IF NOT EXISTS idx_turns_conversation ON turns(conversation_id, seq);
CREATE INDEX IF NOT EXISTS idx_turns_session ON turns(session_id, started_at);
CREATE INDEX IF NOT EXISTS idx_turns_status ON turns(status, started_at DESC);

CREATE INDEX IF NOT EXISTS idx_messages_conversation ON messages(conversation_id, sent_at);
CREATE INDEX IF NOT EXISTS idx_messages_turn ON messages(turn_id, seq);
CREATE INDEX IF NOT EXISTS idx_messages_role ON messages(conversation_id, role, sent_at);
CREATE UNIQUE INDEX IF NOT EXISTS idx_messages_provider_id
  ON messages(session_id, provider_message_id)
  WHERE provider_message_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_thoughts_turn ON thoughts(turn_id, seq);
CREATE INDEX IF NOT EXISTS idx_tool_calls_turn ON tool_calls(turn_id, seq);
CREATE INDEX IF NOT EXISTS idx_tool_calls_name ON tool_calls(tool_name, created_at DESC);

-- "What has any agent read or written under this path?"
CREATE INDEX IF NOT EXISTS idx_document_accesses_uri ON document_accesses(uri, accessed_at DESC);
CREATE INDEX IF NOT EXISTS idx_document_accesses_turn ON document_accesses(turn_id, seq);
CREATE INDEX IF NOT EXISTS idx_document_accesses_conversation ON document_accesses(conversation_id, accessed_at DESC);

-- The approval inbox: everything still waiting on a human.
CREATE INDEX IF NOT EXISTS idx_authorizations_pending ON authorization_requests(decision, requested_at);
