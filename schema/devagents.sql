-- The single ordered stream of everything that happened in a turn: prose, thoughts, tool
-- calls, document reads, approval asks, questions to the human. This is what a renderer
-- walks, and it is why the element tables all carry (turn_id, seq) rather than being
-- shadowed by a separate events table that could drift out of sync.
--
-- Split across two views because D1 builds SQLite with SQLITE_MAX_COMPOUND_SELECT = 5, and
-- there are six element types. Referencing a view counts as one term rather than replaying
-- its branches, so the base carries five and v_turn_timeline adds the sixth. Query
-- v_turn_timeline; the _base half is an implementation detail of that limit.
CREATE VIEW IF NOT EXISTS v_turn_timeline_base AS
  SELECT turn_id, seq, 'message'       AS element_type, id AS element_id, role   AS label, content            AS summary, sent_at      AS occurred_at FROM messages WHERE turn_id IS NOT NULL
  UNION ALL
  SELECT turn_id, seq, 'thought'       AS element_type, id AS element_id, 'thinking', COALESCE(summary, content), created_at   AS occurred_at FROM thoughts
  UNION ALL
  SELECT turn_id, seq, 'tool_call'     AS element_type, id AS element_id, tool_name, COALESCE(result_text, ''), COALESCE(started_at, created_at) FROM tool_calls
  UNION ALL
  SELECT turn_id, seq, 'document'      AS element_type, id AS element_id, access_kind, uri, accessed_at        FROM document_accesses
  UNION ALL
  SELECT turn_id, seq, 'authorization' AS element_type, id AS element_id, decision, title, requested_at        FROM authorization_requests;

CREATE VIEW IF NOT EXISTS v_turn_timeline AS
  SELECT turn_id, seq, element_type, element_id, label, summary, occurred_at FROM v_turn_timeline_base
  UNION ALL
  SELECT turn_id, seq, 'user_prompt'   AS element_type, id AS element_id, status, question, asked_at           FROM user_prompts;

-- Conversation-level accounting, split the way the bill actually arrives: subscription
-- calls consume plan allowance, api calls consume money.
CREATE VIEW IF NOT EXISTS v_conversation_costs AS
  SELECT
    conversation_id,
    COUNT(*)                          AS model_calls,
    SUM(total_tokens)                 AS total_tokens,
    SUM(input_tokens)                 AS input_tokens,
    SUM(output_tokens)                AS output_tokens,
    SUM(reasoning_tokens)             AS reasoning_tokens,
    SUM(cost_usd)                     AS cost_usd,
    SUM(CASE WHEN billing_mode = 'api'          THEN total_tokens ELSE 0 END) AS api_tokens,
    SUM(CASE WHEN billing_mode = 'subscription' THEN total_tokens ELSE 0 END) AS subscription_tokens,
    MIN(recorded_at)                  AS first_call_at,
    MAX(recorded_at)                  AS last_call_at
  FROM usage_records
  GROUP BY conversation_id;

-- Everything currently blocking on a human, across every conversation: the approval and
-- question inbox the UI badge counts.
CREATE VIEW IF NOT EXISTS v_pending_human_actions AS
  SELECT conversation_id, turn_id, id AS element_id, 'authorization' AS element_type,
         title AS prompt, risk_level AS severity, requested_at AS since
    FROM authorization_requests WHERE decision = 'pending'
  UNION ALL
  SELECT conversation_id, turn_id, id AS element_id, 'user_prompt' AS element_type,
         question AS prompt, CASE WHEN is_blocking = 1 THEN 'blocking' ELSE 'optional' END, asked_at
    FROM user_prompts WHERE status = 'pending';
